/**
 * کارام — v1.12.1: تبدیل صداقت صفحات ایستای بیلد بازار
 *
 * صفحات /terms/ و /privacy/ فایل ایستای public هستند و vite آن‌ها را عیناً در
 * dist (و سپس mobile/www → APK بازار) کپی می‌کند. در بیلد بازار (BUILD_MODE=bazaar)
 * بندهای پرداخت (درگاه/کارت‌به‌کارت/اشتراک دوره‌ای) در این صفحات وعده‌ی خرید می‌شوند
 * در حالی که این نسخه هیچ خریدی ندارد — پس در زمان بیلدِ بازار با همین نگاشت به
 * «در این نسخه خریدی انجام نمی‌شود؛ پرو فقط با کد هدیه» تبدیل می‌شوند.
 *
 * بیلد default (latest) هیچ تغییری نمی‌کند.
 *
 * اصل fail-loud: هر نشانه‌ی (marker) که پیدا نشود بیلد شکست می‌خورد — هرگز بی‌صدا
 * صفحه‌ی پرداخت‌دار داخل APK بازار نمی‌ماند. تست قراردادی bun
 * (frontend/tests/bazaar-trust.test.ts) همین تابع را روی فایل public اجرا و راستی‌آزمایی می‌کند.
 */

/**
 * اعمال تبدیل بیلد بازار روی HTML صفحه‌ی ایستا.
 * @param {string} html  محتوای کامل فایل
 * @param {'terms'|'privacy'} page  نام صفحه
 * @returns {string} محتوای تبدیل‌شده
 */
export function applyBazaarStaticTransform(html, page) {
  let out = html;
  /** نگاشت نشانه → جایگزین بازار (هر دو به‌دقت = متن فعلی فایل‌های public) */
  const MAPS = {
    terms: [
      [
        '<meta name="description" content="قوانین استفاده از اپ کارام: مسئولیت محتوا، اشتراک پرو، پرداخت، سوءاستفاده و پشتیبانی.">',
        '<meta name="description" content="قوانین استفاده از اپ کارام: مسئولیت محتوا، فعال‌سازی امکانات ویژه با کد هدیه، سوءاستفاده و پشتیبانی.">',
      ],
      [
        'محتوای کارها متعلق به شماست، اشتراک پرو دوره‌ای است و در پایان دوره داده‌هایتان محفوظ می‌ماند،',
        'محتوای کارها متعلق به شماست، فعال‌سازی امکانات ویژه فقط با کد هدیه است و در پایان دوره داده‌هایتان محفوظ می‌ماند،',
      ],
      [
        '<li><span class="num">۳</span><b>اشتراک پرو:</b> اشتراک پرو دوره‌ای است؛ در پایان دوره اگر تمدید نکنید، اپ به نسخه‌ی رایگان برمی‌گردد ولی هیچ داده‌ای حذف نمی‌شود.</li>',
        '<li><span class="num">۳</span><b>امکانات ویژه:</b> در این نسخه خریدی انجام نمی‌شود؛ فعال‌سازی امکانات ویژه فقط با کد هدیه است. در پایان دوره‌ی فعال‌شده، اپ به نسخه‌ی رایگان برمی‌گردد ولی هیچ داده‌ای حذف نمی‌شود.</li>',
      ],
      [
        '<li><span class="num">۴</span><b>پرداخت:</b> پرداخت از درگاه بانکی (زیبال) یا کارت‌به‌کارت (با تأیید ادمین) است؛ وضعیت هر پرداخت در صفحه‌ی پرو قابل پیگیری است.</li>',
        '<li><span class="num">۴</span><b>کد هدیه:</b> در این نسخه خریدی انجام نمی‌شود؛ پرو فقط با کد هدیه فعال می‌شود.</li>',
      ],
    ],
    privacy: [
      [
        '<td>سفارش اشتراک، واریز کارت‌به‌کارت</td>',
        '<td>فعال‌سازی امکانات ویژه با کد هدیه</td>',
      ],
      [
        '<li><b>پرداخت:</b> برای رسید پرداخت درگاه بانکی (زیبال)، شماره موبایل پرداخت‌کننده به درگاه داده می‌شود — فقط برای همین کار.</li>',
        '<li><b>کد هدیه:</b> در این نسخه خریدی انجام نمی‌شود؛ فعال‌سازی امکانات ویژه فقط با کد هدیه است و در آن هیچ داده‌ای به سرویس بیرونی داده نمی‌شود.</li>',
      ],
    ],
  };
  const map = MAPS[page];
  if (!map) {
    throw new Error(`صفحه‌ی ناشناخته برای تبدیل بازار: ${page}`);
  }
  for (const [marker, replacement] of map) {
    if (!out.includes(marker)) {
      throw new Error(
        `تبدیل بازار (${page}): نشانه‌ی موردانتظار در فایل پیدا نشد — متن public تغییر کرده و نگاشت باید به‌روز شود:\n${marker}`,
      );
    }
    out = out.replace(marker, replacement);
  }
  return out;
}

/** راستی‌آزمایی خروجی: هیچ واژه‌ی ممنوع پرداختی نباید در صفحه‌ی بازار بماند */
export function assertNoBazaarForbiddenWords(html, page) {
  const FORBIDDEN = ['درگاه', 'کارت‌به‌کارت', 'کارت به کارت', 'ارتقا به کارام پرو', 'زیبال'];
  const found = FORBIDDEN.filter((w) => html.includes(w));
  if (found.length > 0) {
    throw new Error(`تبدیل بازار (${page}): واژه‌های ممنوع هنوز در صفحه‌اند: ${found.join('، ')}`);
  }
  return true;
}

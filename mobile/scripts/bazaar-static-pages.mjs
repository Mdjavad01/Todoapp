/**
 * کارام — v1.12.1 + v1.13.3 + v1.13.4: تبدیل صداقت صفحات ایستای بیلد بازار
 *
 * صفحات /terms/ و /privacy/ فایل ایستای public هستند و vite آن‌ها را عیناً در
 * dist (و سپس mobile/www → APK بازار) کپی می‌کند. در بیلد بازار (BUILD_MODE=bazaar)
 * بندهای پرداخت (درگاه/کارت‌به‌کارت/اشتراک دوره‌ای) در این صفحات وعده‌ی خرید می‌شوند
 * در حالی که این نسخه هیچ خریدی و هیچ ورودی فعال‌سازی ندارد — پس در زمان بیلدِ بازار
 * با همین نگاشت به متن خنثیِ «در این نسخه خریدی انجام نمی‌شود» تبدیل می‌شوند.
 * (v1.13.3 — با حذف ورودی کد هدیه از بیلد بازار، جایگزین‌ها هم هیچ اشاره‌ای به
 *  کد هدیه/نسخه‌ی کامل/بیلد karam-latest ندارند — اسکن CI هم رد می‌کند.)
 * (v1.13.4 — جمله‌ی صریح «کافه‌بازار» در نسخه‌ی بازار می‌ماند و ردیف سوابق مالی
 *  به‌جای خنثی‌سازی سلول، به‌طور کامل با یک ردیف بی‌طرف جایگزین می‌شود.)
 *
 * بیلد default (latest) هیچ تغییری نمی‌کند.
 *
 * اصل fail-loud: هر نشانه‌ی (marker) که پیدا نشود بیلد شکست می‌خورد — هرگز بی‌صدا
 * صفحه‌ی پرداخت‌دار داخل APK بازار نمی‌ماند. تست قراردادی bun
 * (frontend/tests/bazaar-trust.test.ts) همین تابع را روی فایل public اجرا و راستی‌آزمایی می‌کند.
 */

/**
 * اعمال تبدیل بیلد بازار روی HTML صفحه‌ی ایستا.
 * @param {string} html  محتوای کامل فایل
 * @param {'terms'|'privacy'} page  نام صفحه
 * @returns {string} محتوای تبدیل‌شده
 */
export function applyBazaarStaticTransform(html, page) {
  let out = html;
  /** نگاشت نشانه → جایگزین بازار (هر دو به‌دقت = متن فعلی فایل‌های public) */
  const MAPS = {
    terms: [
      [
        '<meta name="description" content="قوانین استفاده از اپ کارام: مسئولیت محتوا، اشتراک پرو، پرداخت، سوءاستفاده و پشتیبانی.">',
        '<meta name="description" content="قوانین استفاده از اپ کارام: مسئولیت محتوا، امکانات ویژه، سوءاستفاده و پشتیبانی.">',
      ],
      [
        'محتوای کارها متعلق به شماست، اشتراک پرو دوره‌ای است و در پایان دوره داده‌هایتان محفوظ می‌ماند،',
        'محتوای کارها متعلق به شماست، امکانات ویژه فعلاً در این نسخه فعال نیست و در هر صورت داده‌هایتان محفوظ می‌ماند،',
      ],
      [
        '<li><span class="num">۳</span><b>اشتراک پرو:</b> اشتراک پرو دوره‌ای است؛ در پایان دوره اگر تمدید نکنید، اپ به نسخه‌ی رایگان برمی‌گردد ولی هیچ داده‌ای حذف نمی‌شود.</li>',
        '<li><span class="num">۳</span><b>امکانات ویژه:</b> در این نسخه خریدی انجام نمی‌شود و امکانات ویژه فعلاً فعال نیست؛ در پایان دوره‌ی هر فعال‌سازی، اپ به نسخه‌ی رایگان برمی‌گردد ولی هیچ داده‌ای حذف نمی‌شود.</li>',
      ],
      [
        '<li><span class="num">۴</span><b>پرداخت:</b> پرداخت از درگاه بانکی (زیبال) یا کارت‌به‌کارت (با تأیید ادمین) است؛ وضعیت هر پرداخت در صفحه‌ی پرو قابل پیگیری است.</li>',
        '<li><span class="num">۴</span><b>فعال‌سازی امکانات ویژه:</b> در این نسخه خریدی انجام نمی‌شود و فعال‌سازی امکانات ویژه فعلاً انجام نمی‌شود؛ وضعیت اشتراک فعال در تنظیمات قابل مشاهده است.</li>',
      ],
    ],
    privacy: [
      // v1.13.4 — ردیف «سوابق مالی» فقط در نسخه‌های دارای خرید معنا دارد؛ در بیلد بازار کل ردیف خنثی می‌شود
      [
        `<tr>
        <td>سوابق مالی</td>
        <td>سفارش اشتراک یا واریز (فقط در نسخه‌های دارای خرید)</td>
        <td>سرور</td>
        <td>پس از حذف حساب، <span class="mut">بی‌نام‌شده (بدون هویت)</span> برای الزامات حسابداری می‌ماند</td>
      </tr>`,
        `<tr>
        <td>سوابق مالی</td>
        <td colspan="3">در این نسخه خریدی انجام نمی‌شود و هیچ رکورد مالی ثبت نمی‌شود.</td>
      </tr>`,
      ],
      // v1.13.4 — جمله‌ی صریح «کافه‌بازار» در هر دو نسخه؛ جزئیات زیبال فقط برای نسخه‌های دارای خرید و فقط در نسخه‌ی latest
      [
        '<li><b>پرداخت:</b> در نسخه‌ی منتشرشده در کافه‌بازار هیچ پرداختی انجام نمی‌شود و هیچ اطلاعات پرداخت جمع‌آوری نمی‌شود. فقط در نسخه‌های دارای خرید، برای رسید درگاه بانکی (زیبال)، شماره موبایل پرداخت‌کننده به درگاه داده می‌شود — فقط برای همین کار.</li>',
        '<li><b>پرداخت:</b> در نسخه‌ی منتشرشده در کافه‌بازار هیچ پرداختی انجام نمی‌شود و هیچ اطلاعات پرداخت جمع‌آوری نمی‌شود.</li>',
      ],
    ],
  };
  const map = MAPS[page];
  if (!map) {
    throw new Error(`صفحه‌ی ناشناخته برای تبدیل بازار: ${page}`);
  }
  for (const [marker, replacement] of map) {
    if (!out.includes(marker)) {
      throw new Error(
        `تبدیل بازار (${page}): نشانه‌ی موردانتظار در فایل پیدا نشد — متن public تغییر کرده و نگاشت باید به‌روز شود:\n${marker}`,
      );
    }
    out = out.replace(marker, replacement);
  }
  return out;
}

/** راستی‌آزمایی خروجی: هیچ واژه‌ی ممنوع پرداختی/ارجاع بیرونی نباید در صفحه‌ی بازار بماند (v1.13.3) */
export function assertNoBazaarForbiddenWords(html, page) {
  const FORBIDDEN = [
    'درگاه',
    'کارت‌به‌کارت',
    'کارت به کارت',
    'ارتقا به کارام پرو',
    'زیبال',
    // v1.13.3 — با حذف ورودی کد هدیه از بیلد بازار، هیچ اشاره‌ای به آن و به بیلد/نسخه‌ی خارج از بازار مجاز نیست
    'کد هدیه',
    'karam-latest',
    'نسخه کامل',
    'نسخه‌ی کامل',
    'نسخهٔ کامل',
  ];
  const found = FORBIDDEN.filter((w) => html.includes(w));
  if (found.length > 0) {
    throw new Error(`تبدیل بازار (${page}): واژه‌های ممنوع هنوز در صفحه‌اند: ${found.join('، ')}`);
  }
  return true;
}
